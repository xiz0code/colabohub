insert into users (email, full_name, auth_provider, provider_subject, active, last_login_at, created_at, updated_at)
select
    au.email,
    au.full_name,
    'GOOGLE',
    au.google_subject,
    au.active,
    null,
    au.created_at,
    au.updated_at
from app_users au
where not exists (
    select 1
    from users u
    where lower(u.email) = lower(au.email)
);

insert into user_roles (user_id, role_id)
select u.id, au.role_id
from app_users au
join users u on lower(u.email) = lower(au.email)
where not exists (
    select 1
    from user_roles ur
    where ur.user_id = u.id and ur.role_id = au.role_id
);

insert into user_store_access (user_id, store_id)
select u.id, su.store_id
from store_users su
join app_users au on au.id = su.user_id
join users u on lower(u.email) = lower(au.email)
where su.active = true
  and not exists (
      select 1
      from user_store_access usa
      where usa.user_id = u.id and usa.store_id = su.store_id
  );

create index if not exists idx_users_email on users (email);
create index if not exists idx_user_roles_user on user_roles (user_id);
create index if not exists idx_user_market_access_user on user_market_access (user_id);
create index if not exists idx_user_store_access_user on user_store_access (user_id);
