create table if not exists users (
    id bigint generated by default as identity primary key,
    email varchar(180) not null unique,
    full_name varchar(180) not null,
    auth_provider varchar(40) not null,
    provider_subject varchar(180),
    active boolean not null default true,
    last_login_at timestamp with time zone,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create table if not exists user_roles (
    user_id bigint not null,
    role_id bigint not null,
    constraint fk_user_roles_user foreign key (user_id) references users (id),
    constraint fk_user_roles_role foreign key (role_id) references roles (id),
    constraint uk_user_roles unique (user_id, role_id)
);

create table if not exists user_market_access (
    user_id bigint not null,
    market_id bigint not null,
    constraint fk_user_market_access_user foreign key (user_id) references users (id),
    constraint fk_user_market_access_market foreign key (market_id) references markets (id),
    constraint uk_user_market_access unique (user_id, market_id)
);

create table if not exists user_store_access (
    user_id bigint not null,
    store_id bigint not null,
    constraint fk_user_store_access_user foreign key (user_id) references users (id),
    constraint fk_user_store_access_store foreign key (store_id) references stores (id),
    constraint uk_user_store_access unique (user_id, store_id)
);

